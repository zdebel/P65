"""The P65 machine: 65C02 + memory map + I/O, modelled on the Pico firmware.

Memory map (src/mapper.h):
    $0000-$7FFF  RAM (32 KB)
    $8000        LEDs       write: bits 0-2 = LED0..2 (1 = on); read: $F8|leds
    $8001        keyboard   bit 7 = new key; any write clears bit 7
    $8002        VDP data   (read/write, auto-increment)
    $8003        VDP        read = status (clears it), write = address/register
    $8004-$80FF  unused     writes ignored, reads 0
    $8100-$FFFF  ROM (32512 bytes, writes ignored)
"""

import base64
import collections
import json
import os
import re

from cpu65c02 import CPU65C02
from tms9918 import TMS9918
from memmap import (RAM_END, IO_START, IO_END, ROM_START, ROM_END, ROM_SIZE,
                    IO_LEDS, IO_KEY, IO_VDATA, IO_VCTRL, IO_STORAGE)
import storage as sto

CPU_CLOCK = 2_000_000           # PIO: 200 MHz / 3.5714 / 28 = 2 MHz
FRAME_RATE = 60
FRAME_CYCLES = CPU_CLOCK // FRAME_RATE
# The firmware hands a queued key to the CPU every few microseconds; here it
# happens between CPU slices, so slices are kept short.
SLICE_CYCLES = FRAME_CYCLES // 8
# While the IRQ pin is (or was just) asserted the machine works in short
# slices, so that the pin's release after a status read can be timed.
IRQ_SLICE_CYCLES = 32
# On the real board the pin is driven through the I2C expander (core 0 polls
# the VDP and writes the PCAL6524): releasing it takes a while after the CPU
# read the status register, so a short ISR may be entered once or twice more.
# Calibrated on the board (vsync.bin demo, full firmware): ~7-8 empty handler
# entries per frame, which the emulator reproduces with ~100 us (the emulator
# works in 32-cycle slices, so this number is not the real delay itself).
# 0 = ideal interrupt controller.
DEFAULT_IRQ_RELEASE_US = 100


HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)


def load_rom_h(path):
    """Parse include/rom.h (generated by tools/bin2rom) into bytes."""
    with open(path, 'r', encoding='latin-1') as f:
        text = f.read()
    body = text.split('{', 1)[1].split('}', 1)[0]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return bytes(int(v, 16) for v in re.findall(r'0x([0-9A-Fa-f]{2})', body))


def load_basic_init(path):
    """Parse the Ctrl+= demo program (ram_basic_init[] + end) from mapper.c."""
    with open(path, 'r', encoding='utf-8', errors='replace') as f:
        text = f.read()
    m = re.search(r'ram_basic_init\[\]\s*=\s*\{(.*?)\}', text, re.S)
    if not m:
        return None
    data = bytes(int(v, 16) for v in re.findall(r'0x([0-9A-Fa-f]{1,2})', m.group(1)))
    start = re.search(r'ram_basic_init_start\s*=\s*0x([0-9A-Fa-f]+)', text)
    end = re.search(r'ram_basic_init_end\s*=\s*0x([0-9A-Fa-f]+)', text)
    return (data,
            int(start.group(1), 16) if start else 0x0401,
            int(end.group(1), 16) if end else 0x0401 + len(data))


def default_rom():
    """The ROM the firmware is built with, else the matching .bin."""
    for path in (os.path.join(PROJECT, 'include', 'rom.h'),):
        if os.path.exists(path):
            return load_rom_h(path), path
    path = os.path.join(HERE, 'rom', 'p65_basic.bin')          # standalone checkout of the emulator
    if os.path.exists(path):
        with open(path, 'rb') as f:
            return f.read(), path
    path = os.path.join(PROJECT, 'asm_examples', 'testrom1.bin')
    if os.path.exists(path):
        with open(path, 'rb') as f:
            return f.read(), path
    return None, None


class Keyboard:
    """Keyboard register $8001 exactly like src/keyboard.c:
    a press queues the character (max 7 waiting, like the 8-slot ring);
    the next one is handed over only after the CPU acknowledged the previous
    one (wrote $8001); when every key is released and nothing is pending,
    $8001 reads 0 again. Pasted text uses its own unlimited queue."""

    QUEUE_MAX = 7

    def __init__(self, mem):
        self.mem = mem
        self.queue = collections.deque()
        self.paste = collections.deque()
        self.held = set()

    def reset(self):
        self.queue.clear()
        self.paste.clear()
        self.held.clear()
        self.mem[IO_KEY] = 0

    def press(self, key_id, ch):
        if key_id is not None:
            self.held.add(key_id)
        if ch is not None and len(self.queue) < self.QUEUE_MAX:
            self.queue.append(ch & 0x7F)

    def release(self, key_id):
        self.held.discard(key_id)

    def release_all(self):
        self.held.clear()

    def type_text(self, text):
        for ch in text:
            self.paste.append(ord(ch) & 0x7F)

    def pending(self):
        return len(self.queue) + len(self.paste)

    def deliver(self):
        m = self.mem
        if m[IO_KEY] & 0x80:
            return
        if self.queue:
            m[IO_KEY] = self.queue.popleft() | 0x80
        elif self.paste:
            m[IO_KEY] = self.paste.popleft() | 0x80
        elif not self.held and m[IO_KEY]:
            m[IO_KEY] = 0


class P65:
    def __init__(self):
        # +2 bytes so 16-bit operand fetches at $FFFF never index past the end
        self.mem = bytearray(0x10000 + 2)
        self.vdp = TMS9918()
        self.kbd = Keyboard(self.mem)
        self.cpu = CPU65C02(self.mem, self._rd_io, self._wr_io)
        self.leds = 0
        self.led_writes = 0
        self.rom = bytes([0xFF]) * ROM_SIZE
        self.rom_name = '(none)'
        self.frame_pos = 0              # cycles into the current frame
        self.frames = 0
        self.abs_cycles = 0             # emulated time, also while the CPU is halted
        self.irq_release_us = DEFAULT_IRQ_RELEASE_US
        self._irq_release_at = None
        # storage (flash file system, the same code as the firmware) behind the mailbox registers
        self.store = None
        self.storage_error = None
        self._sto_done_at = None        # abs_cycles when the running command completes
        self._sto_result = 0
        self.open_storage()
        self.basic_init = None
        mapper = os.path.join(PROJECT, 'src', 'mapper.c')
        if os.path.exists(mapper):
            self.basic_init = load_basic_init(mapper)

    # ------------------------------------------------------------ storage
    def open_storage(self, path=sto.DEFAULT_IMAGE):
        """(Re)open the storage image the CPU sees through the mailbox. Returns True on success."""
        if self.store is not None:
            self.store.close()
            self.store = None
        self.storage_error = None
        try:
            self.store = sto.Store(path)
        except sto.StorageError as e:
            self.storage_error = str(e)
        self._sto_done_at = None
        self._storage_regs_reset()
        return self.store is not None

    def _storage_regs_reset(self):
        for k in range(sto.STO_REG_COUNT):
            self.mem[IO_STORAGE + k] = 0
        if self.store is not None:
            self.store.init_regs(self.mem, IO_STORAGE)

    def _storage_command(self):
        if self.store is None or self._sto_done_at is not None:
            return                                      # no storage hardware / still busy: ignored
        m = self.mem
        erases, programs = self.store.execute(m, RAM_END, IO_STORAGE)
        result = m[IO_STORAGE + sto.STO_STATUS]
        nbytes = m[IO_STORAGE + sto.STO_LEN_L] | m[IO_STORAGE + sto.STO_LEN_H] << 8
        ms = 0.3 + sto.op_time_ms(erases, programs, nbytes)
        self._sto_result = result
        m[IO_STORAGE + sto.STO_STATUS] = sto.STO_BUSY    # the CPU sees BUSY until the flash would be done
        self._sto_done_at = self.abs_cycles + max(1, int(ms * CPU_CLOCK / 1000))

    def _update_storage(self):
        if self._sto_done_at is not None and self.abs_cycles >= self._sto_done_at:
            self.mem[IO_STORAGE + sto.STO_STATUS] = self._sto_result
            self._sto_done_at = None

    # ------------------------------------------------------------ I/O
    def _rd_io(self, addr):
        if addr == IO_VDATA:
            return self.vdp.read_data()
        return self.vdp.read_status()           # $8003

    def _wr_io(self, addr, v):
        if addr == IO_VDATA:
            self.vdp.write_data(v)
        elif addr == IO_VCTRL:
            self.vdp.write_addr(v)
        elif addr == IO_KEY:
            self.mem[IO_KEY] &= 0x7F            # acknowledge key
        elif IO_STORAGE <= addr < IO_STORAGE + sto.STO_REG_COUNT:
            off = addr - IO_STORAGE
            if off not in (sto.STO_STATUS, sto.STO_ID, sto.STO_VERSION):     # read-only registers
                self.mem[addr] = v
                if off == sto.STO_CMD:
                    self._storage_command()
        elif addr == IO_LEDS:
            self.leds = v & 7
            self.led_writes += 1
            self.mem[IO_LEDS] = 0xF8 | self.leds  # firmware: ~(p2 >> 5)
        # $8004-$80FF: ignored (e.g. AY-3-8910 writes at $8008/$8009)

    # ------------------------------------------------------------ setup
    def load_rom(self, data, name='ROM'):
        data = bytes(data[:ROM_SIZE])
        self.rom = data + bytes([0xFF]) * (ROM_SIZE - len(data))
        self.rom_name = name

    def power_on(self):
        """Cold start, like main(): clear RAM, copy ROM, reset VDP and CPU."""
        m = self.mem
        m[0:ROM_START] = bytes(ROM_START)
        m[ROM_START:ROM_END + 1] = self.rom
        m[0x10000:] = bytes(2)
        self.leds = 7                    # P2 bits 5-7 low after the boot sequence
        m[IO_LEDS] = 0xFF
        self.kbd.reset()
        self.vdp.reset()
        self._sto_done_at = None
        self._storage_regs_reset()
        self.cpu.cycles = 0
        self.cpu.reset()
        self.cpu.irq = 0
        self._irq_release_at = None
        self.frame_pos = 0

    def reset(self):
        """CPU reset only (RAM and VDP keep their contents)."""
        self.kbd.reset()
        self.cpu.reset()
        self.cpu.irq = 0
        self._irq_release_at = None

    def _update_irq(self):
        """Drive the CPU's /IRQ pin from the VDP's INT output, like the
        firmware's video_poll(): asserted as soon as INT is set, released
        irq_release_us after the CPU has read the status register."""
        cpu = self.cpu
        if self.vdp.irq_pending():
            cpu.irq = 1
            self._irq_release_at = None
        elif cpu.irq:
            if self._irq_release_at is None:
                self._irq_release_at = self.abs_cycles + self.irq_release_us * (CPU_CLOCK // 1_000_000)
            if self.abs_cycles >= self._irq_release_at:
                cpu.irq = 0
                self._irq_release_at = None
        if cpu.halted == 1 and cpu.irq:     # WAI: any IRQ wakes the CPU
            cpu.halted = 0
            cpu.pc = (cpu.pc + 1) & 0xFFFF

    def init_basic(self):
        """Ctrl+= : mapper_init_basic() - drop the demo program into RAM."""
        if not self.basic_init:
            return False
        data, start, end = self.basic_init
        m = self.mem
        m[0x67], m[0x68] = start & 0xFF, start >> 8
        m[0x69], m[0x6A] = end & 0xFF, end >> 8
        m[0xAF], m[0xB0] = end & 0xFF, end >> 8
        m[0x0401:0x0401 + len(data)] = data
        return True

    def load_binary(self, data, addr):
        """Load bytes into memory (RAM part only is writable from the CPU,
        but loading into ROM space is allowed here, like reflashing)."""
        end = min(addr + len(data), 0x10000)
        self.mem[addr:end] = data[:end - addr]
        if end > ROM_START:
            lo = max(addr, ROM_START)
            rom = bytearray(self.rom)
            rom[lo - ROM_START:end - ROM_START] = self.mem[lo:end]
            self.rom = bytes(rom)

    # ------------------------------------------------------------ running
    def run(self, cycles):
        """Run for `cycles` CPU cycles. Returns (cycles_run, frames_rendered,
        stopped) - stopped is True on a breakpoint."""
        done = 0
        rendered = 0
        cpu = self.cpu
        kbd = self.kbd
        while done < cycles:
            kbd.deliver()
            self._update_irq()
            self._update_storage()
            n = min(SLICE_CYCLES, cycles - done, FRAME_CYCLES - self.frame_pos)
            if cpu.irq or self._irq_release_at is not None:
                n = min(n, IRQ_SLICE_CYCLES)
            if cpu.halted:
                ran = n                     # WAI/STP: time passes, nothing runs
            else:
                ran = cpu.run(n)
                if cpu.hit_breakpoint:
                    self.frame_pos += ran
                    self.abs_cycles += ran
                    return done + ran, rendered, True
            self.abs_cycles += ran
            done += ran
            self.frame_pos += ran
            if self.frame_pos >= FRAME_CYCLES:
                self.frame_pos -= FRAME_CYCLES
                self.frames += 1
                if self.vdp.end_frame():
                    rendered += 1
        return done, rendered, False

    def step(self):
        self.kbd.deliver()
        self._update_irq()
        self._update_storage()
        n = self.cpu.step()
        self.abs_cycles += n
        self.frame_pos += n
        if self.frame_pos >= FRAME_CYCLES:
            self.frame_pos -= FRAME_CYCLES
            self.vdp.end_frame()
        return n

    # ------------------------------------------------------------ snapshots
    def save_state(self, path):
        s = {
            'format': 'p65-state-1',
            'mem': base64.b64encode(bytes(self.mem[:0x10000])).decode(),
            'rom': base64.b64encode(self.rom).decode(),
            'rom_name': self.rom_name,
            'cpu': self.cpu.state(),
            'vdp': {k: (base64.b64encode(v).decode() if k == 'vram' else v)
                    for k, v in self.vdp.state().items()},
            'leds': self.leds,
            'frame_pos': self.frame_pos,
        }
        with open(path, 'w') as f:
            json.dump(s, f)

    def load_state(self, path):
        with open(path, 'r') as f:
            s = json.load(f)
        if s.get('format') != 'p65-state-1':
            raise ValueError('Not a P65 state file')
        self.mem[:0x10000] = base64.b64decode(s['mem'])
        self.rom = base64.b64decode(s['rom'])
        self.rom_name = s.get('rom_name', 'ROM')
        self.cpu.set_state(s['cpu'])
        v = dict(s['vdp'])
        v['vram'] = base64.b64decode(v['vram'])
        self.vdp.set_state(v)
        self.leds = s.get('leds', 0)
        self.frame_pos = s.get('frame_pos', 0)
        self.kbd.reset()
        self.mem[IO_KEY] = 0
